/**
 * Модель товара, с которой работает всё приложение.
 *
 * @module
 */

/**
 * Товар на складе. Имя `Topic` взято из методички, по смыслу это товар.
 * Это модель приложения: экраны работают только с ней, а не с тем, что прислал сервер.
 */
export type Topic = {
  /** Уникальный номер товара. Строкой, потому что так удобнее использовать в адресе и как ключ списка. */
  id: string;
  /** Название товара. */
  title: string;
  /** Описание товара. */
  description: string;
  /** Ссылка на картинку. Необязательное поле: если его нет, рисуется заглушка «Нет фото». */
  imageUrl?: string;
  /** Категория товара в виде кода, например `beauty`. Русское название даёт `getCategoryLabel`. */
  category: string;
  /** Бренд. Необязательное поле: примерно у половины товаров бренда нет. */
  brand?: string;
  /** Артикул — код товара, по нему тоже работает поиск. */
  sku: string;
  /** Остаток на складе в штуках. По нему определяется статус «В наличии / Мало / Нет». */
  stock: number;
  /** Цена в долларах. */
  price: number;
  /** Минимальная партия заказа в штуках. Необязательное поле. */
  minimumOrderQuantity?: number;
};
