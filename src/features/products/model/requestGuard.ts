/**
 * Защита от устаревших ответов сервера.
 * Если отправить два запроса подряд, ответ первого может прийти позже второго и перезаписать правильный результат.
 *
 * @module
 */

/** Счётчик запросов, который умеет говорить, какой запрос последний. */
export type RequestGuard = {
  /**
   * Отмечает начало нового запроса.
   * Возвращает функцию-проверку: она отвечает `true`, только пока этот запрос последний.
   */
  start: () => () => boolean;
};

/**
 * Создаёт новый счётчик запросов. У каждого хука, который ходит в сеть, свой счётчик.
 *
 * @returns Объект с методом `start`.
 */
export function createRequestGuard(): RequestGuard {
  /** Номер последнего начатого запроса. */
  let lastId = 0;

  return {
    /**
     * Увеличивает номер и запоминает его для этого запроса.
     * Когда придёт ответ, вызывается возвращённая функция: если номер всё ещё последний — ответ актуальный.
     */
    start() {
      lastId += 1;
      const id = lastId;
      return () => id === lastId;
    },
  };
}
