/**
 * Проверка номера товара, который пришёл из адреса (`/topic/16`).
 *
 * @module
 */

/**
 * Проверяет, что в адресе правильный номер товара.
 *
 * TypeScript не может проверить адрес заранее: ссылку может прислать кто угодно, например `/topic/abc`.
 * Поэтому проверка во время работы, регулярным выражением: первая цифра от 1 до 9, дальше любые цифры.
 * Подходят `1`, `47`, `194`. Не подходят `abc`, `0`, `-5`, `1.5`, `01`.
 *
 * @param value - Параметр из адреса. Может быть строкой, массивом строк или отсутствовать.
 * @returns Номер, если он правильный, иначе `undefined`. С `undefined` карточка не делает запрос.
 */
export function parseTopicId(value: unknown): string | undefined {
  if (typeof value !== 'string') return undefined;
  return /^[1-9]\d*$/.test(value) ? value : undefined;
}
